const blogGrid = document.getElementById('blogGrid');
const searchInput = document.getElementById('searchInput');
const themeToggle = document.getElementById('themeToggle');
const themeIcon = document.getElementById('themeIcon');
const articleModal = document.getElementById('articleModal');
const closeModal = document.getElementById('closeModal');

const modalTitle = document.getElementById('modalTitle');
const modalCategory = document.getElementById('modalCategory');
const modalDate = document.getElementById('modalDate');
const modalContent = document.getElementById('modalContent');

function renderArticles(data) {
    blogGrid.innerHTML = '';
    
    if (data.length === 0) {
        blogGrid.innerHTML = `<p style="grid-column: 1/-1; text-align: center; color: var(--md-sys-color-outline);">Artikel tidak ditemukan.</p>`;
        return;
    }

    data.forEach(article => {
        const card = document.createElement('div');
        card.className = 'blog-card';
        card.innerHTML = `
            <img src="${article.image}" alt="${article.title}" class="card-img">
            <div class="card-content">
                <span class="badge">${article.category}</span>
                <h3 class="card-title">${article.title}</h3>
                <p class="card-snippet">${article.snippet}</p>
                <div class="card-footer">
                    <span>${article.date}</span>
                    <span class="material-symbols-outlined" style="font-size: 1.2rem;">arrow_forward</span>
                </div>
            </div>
        `;
        card.addEventListener('click', () => openModal(article));
        blogGrid.appendChild(card);
    });
}

function openModal(article) {
    modalTitle.textContent = article.title;
    modalCategory.textContent = article.category;
    modalDate.textContent = article.date;
    
    // Gunakan innerHTML alih-alih teks biasa agar tag HTML (seperti <b>, <i>, <br>) berfungsi
    modalContent.innerHTML = article.content.map(paragraf => `<p>${paragraf}</p>`).join('');
    
    articleModal.classList.add('active');
}

function closeModalFunc() {
    articleModal.classList.remove('active');
}

closeModal.addEventListener('click', closeModalFunc);
articleModal.addEventListener('click', (e) => {
    if (e.target === articleModal) closeModalFunc();
});

searchInput.addEventListener('input', (e) => {
    const keyword = e.target.value.toLowerCase();
    const filtered = articles.filter(item => 
        item.title.toLowerCase().includes(keyword) || 
        item.snippet.toLowerCase().includes(keyword) ||
        item.category.toLowerCase().includes(keyword)
    );
    renderArticles(filtered);
});

themeToggle.addEventListener('click', () => {
    const currentTheme = document.documentElement.getAttribute('data-theme');
    if (currentTheme === 'dark') {
        document.documentElement.removeAttribute('data-theme');
        themeIcon.textContent = 'dark_mode';
        localStorage.setItem('theme', 'light');
    } else {
        document.documentElement.setAttribute('data-theme', 'dark');
        themeIcon.textContent = 'light_mode';
        localStorage.setItem('theme', 'dark');
    }
});

window.addEventListener('DOMContentLoaded', () => {
    const savedTheme = localStorage.getItem('theme');
    if (savedTheme === 'dark') {
        document.documentElement.setAttribute('data-theme', 'dark');
        themeIcon.textContent = 'light_mode';
    }
    renderArticles(articles);
});
